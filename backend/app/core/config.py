"""Application configuration module using Pydantic Settings."""

from collections import Counter
import math
from typing import Any, List, Optional, Set, Tuple
from pydantic import Field, SecretStr, model_validator
from pydantic_settings import BaseSettings, PydanticBaseSettingsSource, SettingsConfigDict

ALLOWED_ENVIRONMENTS: Set[str] = {"development", "test", "staging", "production"}

KNOWN_INSECURE_SECRETS: Set[str] = {
    "auren-journal-hmac-test-secret-change-in-prod",
    "auren_dev_hmac_secret_32_chars_long_entropy_ok!",
    "auren_test_hmac_secret_32_chars_dev_only!!",
    "test_default_hmac_secret_32_chars_entropy_ok!",
    "changeme",
    "secret",
    "password",
    "default",
    "test",
    "1234567890",
    "admin",
    "root",
}


def calculate_shannon_entropy(s: str) -> float:
    """Calculates Shannon entropy in bits per character."""
    if not s:
        return 0.0
    counts = Counter(s)
    n = len(s)
    return -sum((c / n) * math.log2(c / n) for c in counts.values())


def validate_cryptographic_secret_strength(secret_val: str, env: str) -> None:
    """Validates that a secret satisfies minimum strength criteria as a screening measure.

    NOTE: Heuristic metrics such as Shannon entropy and character-variety checks are
    defensive screening filters to reject accidentally weak or default strings. They do
    NOT provide mathematical proof that a secret was generated by a CSPRNG.

    Production and staging secrets MUST be generated using a cryptographically secure
    random number generator (CSPRNG):
      - OpenSSL (CLI): openssl rand -hex 32
      - Python:        python3 -c "import secrets; print(secrets.token_urlsafe(32))"

    Never reveals the secret value in exception messages, logs, or API responses.
    """
    if secret_val.lower() in KNOWN_INSECURE_SECRETS:
        raise ValueError(
            f"JOURNAL_HMAC_SECRET cannot be a known default or insecure test value in {env}."
        )

    if len(secret_val) < 32:
        raise ValueError(
            f"JOURNAL_HMAC_SECRET must be at least 32 characters (256 bits) in {env}; got {len(secret_val)} characters."
        )

    # Reject low character variety
    unique_count = len(set(secret_val))
    if unique_count < 12:
        raise ValueError(
            f"JOURNAL_HMAC_SECRET has insufficient character variety ({unique_count} unique characters in {env}). "
            f"Generate a secure random secret using: openssl rand -hex 32"
        )

    # Reject low Shannon entropy (defensive screening filter)
    entropy = calculate_shannon_entropy(secret_val)
    if entropy < 3.0:
        raise ValueError(
            f"JOURNAL_HMAC_SECRET has insufficient entropy ({entropy:.2f} bits/character < 3.0 required in {env}). "
            f"Generate a secure random secret using: openssl rand -hex 32"
        )

    # Reject predictable sequential characters (e.g. '12345678' or 'abcdefgh')
    consecutive_run = 1
    for i in range(len(secret_val) - 1):
        if ord(secret_val[i + 1]) == ord(secret_val[i]) + 1:
            consecutive_run += 1
            if consecutive_run >= 6:
                raise ValueError(
                    f"JOURNAL_HMAC_SECRET contains predictable sequential characters in {env}. "
                    f"Generate a secure random secret using: openssl rand -hex 32"
                )
        else:
            consecutive_run = 1


class SecretMaskingSource(PydanticBaseSettingsSource):
    """Public settings source wrapper ensuring JOURNAL_HMAC_SECRET is immediately wrapped in SecretStr.

    This ensures that raw secret strings loaded from environment variables or .env files
    never appear in Pydantic's ValidationError input_value representation across all supported
    pydantic-settings versions.
    """

    def __init__(self, target: PydanticBaseSettingsSource):
        self.target = target

    def get_field_value(self, field: Any, field_name: str) -> Tuple[Any, str, bool]:
        val, key, is_complex = self.target.get_field_value(field, field_name)
        if key == "JOURNAL_HMAC_SECRET" and isinstance(val, str):
            val = SecretStr(val)
        return val, key, is_complex

    def __call__(self) -> dict[str, Any]:
        data = self.target()
        if "JOURNAL_HMAC_SECRET" in data and isinstance(data["JOURNAL_HMAC_SECRET"], str):
            data["JOURNAL_HMAC_SECRET"] = SecretStr(data["JOURNAL_HMAC_SECRET"])
        return data

    def __getattr__(self, item: str) -> Any:
        return getattr(self.target, item)


class Settings(BaseSettings):
    """Central configuration for the AUREN backend application."""

    model_config = SettingsConfigDict(
        env_file=(".env", "backend/.env"),
        env_file_encoding="utf-8",
        extra="ignore",
    )

    def __init__(self, **values: Any):
        if "JOURNAL_HMAC_SECRET" in values and isinstance(values["JOURNAL_HMAC_SECRET"], str):
            values["JOURNAL_HMAC_SECRET"] = SecretStr(values["JOURNAL_HMAC_SECRET"])
        super().__init__(**values)

    @classmethod
    def settings_customise_sources(
        cls,
        settings_cls: type[BaseSettings],
        init_settings: PydanticBaseSettingsSource,
        env_settings: PydanticBaseSettingsSource,
        dotenv_settings: PydanticBaseSettingsSource,
        file_secret_settings: PydanticBaseSettingsSource,
    ) -> tuple[PydanticBaseSettingsSource, ...]:
        return tuple(
            SecretMaskingSource(s)
            for s in (init_settings, env_settings, dotenv_settings, file_secret_settings)
        )

    # Application settings
    APP_NAME: str = "AUREN Personal AI API"
    APP_VERSION: str = "0.1.1"
    ENVIRONMENT: str = Field(default="development", description="development, staging, or production")
    HOST: str = "0.0.0.0"
    PORT: int = 8000
    CORS_ORIGINS: List[str] = [
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "http://localhost:3000",
    ]

    # Supabase Configuration
    SUPABASE_URL: Optional[str] = None
    SUPABASE_ANON_KEY: Optional[str] = None
    SUPABASE_JWT_SECRET: Optional[str] = None
    SUPABASE_JWKS_URL: Optional[str] = None

    # Replaceable AI Provider Configuration
    LLM_PROVIDER: str = "gemini"
    LLM_API_KEY: Optional[str] = None
    LLM_MODEL: str = "gemini-2.0-flash"
    GROQ_API_KEY: Optional[str] = None
    OPENAI_API_KEY: Optional[str] = None

    # Replaceable Embedding Provider Configuration
    EMBEDDING_PROVIDER: str = "gemini"
    EMBEDDING_API_KEY: Optional[str] = None
    EMBEDDING_MODEL: str = "gemini-embedding-2"

    # Chat & Stream Configuration
    CHAT_REPOSITORY_TYPE: str = Field(default="auto", description="'auto', 'supabase', or 'sqlite'")
    CHAT_MAX_MESSAGE_LENGTH: int = 10000
    CHAT_STREAM_TIMEOUT_SECONDS: int = 60
    CHAT_STREAM_HEARTBEAT_SECONDS: float = 15.0
    CHAT_HISTORY_LIMIT: int = 40

    # Persistent Memory Pipeline & Hybrid Retrieval Configuration
    MEMORY_EXTRACTION_ENABLED: bool = True
    MEMORY_RETRIEVAL_ENABLED: bool = True
    MEMORY_CONTEXT_BUDGET_TOKENS: int = 500
    MEMORY_SEARCH_LIMIT: int = 5
    MEMORY_SIMILARITY_THRESHOLD: float = 0.0

    # Memory Extraction Background Worker Configuration
    WORKER_DATABASE_URL: Optional[str] = None
    DATABASE_URL: Optional[str] = None
    MEMORY_WORKER_ENABLED: bool = True
    MEMORY_WORKER_POLL_INTERVAL_SECONDS: float = 2.0
    MEMORY_WORKER_BATCH_SIZE: int = 5
    MEMORY_WORKER_LEASE_SECONDS: int = 300
    MEMORY_WORKER_CONCURRENCY: int = 2

    # Journal Privacy & Consent Configuration
    JOURNAL_HMAC_SECRET: Optional[SecretStr] = Field(
        default=None,
        description="Backend HMAC secret for journal consent verification (minimum 32 characters in staging/production)",
    )

    @model_validator(mode="after")
    def validate_journal_hmac_secret(self) -> "Settings":
        raw_env = (self.ENVIRONMENT or "").strip()
        env = raw_env.lower()
        if env not in ALLOWED_ENVIRONMENTS:
            raise ValueError(
                f"Unsupported ENVIRONMENT '{self.ENVIRONMENT}'. Must be one of: "
                f"{', '.join(sorted(ALLOWED_ENVIRONMENTS))}."
            )

        secret_val = self.JOURNAL_HMAC_SECRET.get_secret_value() if self.JOURNAL_HMAC_SECRET else None

        if not secret_val or not secret_val.strip():
            raise ValueError(
                f"JOURNAL_HMAC_SECRET must be explicitly configured in {env} environment."
            )

        if env in ("production", "staging"):
            validate_cryptographic_secret_strength(secret_val, env)
        else:
            # development or test
            if len(secret_val) < 16:
                raise ValueError(
                    f"JOURNAL_HMAC_SECRET must be at least 16 characters in {env} environment; "
                    f"got {len(secret_val)} characters."
                )
        return self

    def get_journal_hmac_secret(self) -> str:
        """Returns the raw secret string for cryptographic operations. Never expose in logs or APIs."""
        if not self.JOURNAL_HMAC_SECRET:
            raise ValueError("JOURNAL_HMAC_SECRET is not configured.")
        return self.JOURNAL_HMAC_SECRET.get_secret_value()


settings = Settings()


def get_journal_hmac_secret() -> str:
    """Convenience helper returning the configured HMAC secret from central settings."""
    return settings.get_journal_hmac_secret()

