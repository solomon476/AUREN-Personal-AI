/**
 * Strict sanitization policy:
 * - Extends defaultSchema to permit safe MathML and KaTeX markup elements.
 * - Allows syntax highlighting classes generated by highlight.js.
 * - Forbids all script tags, iframe, object, embed, event handlers, and unsafe URL protocols.
 */
export const markdownSanitizeSchema = {
  ...defaultSchema,
  tagNames: [
    ...(defaultSchema.tagNames || []),
    'math',
    'semantics',
    'mrow',
    'mi',
    'mo',
    'mn',
    'annotation',
    'mtext',
    'msup',
    'msub',
    'mfrac',
    'msqrt',
    'mspace',
    'svg',
    'path',
  ],
  attributes: {
    ...defaultSchema.attributes,
    span: [
      ...(defaultSchema.attributes?.span || []),
      ['className', /^hljs-/, /^katex/, /^math-/],
      'aria-hidden',
      'style',
    ],
    code: [
      ...(defaultSchema.attributes?.code || []),
      ['className', /^language-/, /^hljs/],
    ],
    div: [
      ...(defaultSchema.attributes?.div || []),
      ['className', /^katex-display/],
    ],
    math: ['xmlns', 'display'],
    annotation: ['encoding'],
    svg: ['width', 'height', 'viewBox', 'aria-hidden'],
    path: ['d'],
  },
  protocols: {
    ...defaultSchema.protocols,
    href: ['http', 'https', 'mailto'],
  },
};

export type ActionLifecycleStatus =
  | 'proposed'
  | 'awaiting_confirmation'
  | 'executing'
  | 'completed'
  | 'failed';

interface ActionStateRecord {
  status: ActionLifecycleStatus;
  entityId?: string;
  error?: string;
  updatedAt: string;
}

interface MessageContextValue {
  conversationId?: string;
  messageId?: string;
}

export const MessageContext = React.createContext<MessageContextValue>({});

const getStoredActionState = (key: string): ActionStateRecord | null => {
  try {
    const raw = localStorage.getItem(key);
    if (raw) return JSON.parse(raw);
  } catch {
    // Ignore storage parse exceptions
  }
  return null;
};

const persistActionState = (key: string, record: ActionStateRecord) => {
  try {
    localStorage.setItem(key, JSON.stringify(record));
  } catch {
    // Ignore storage write exceptions
  }
};

const checkExistingEntity = async (action: any): Promise<boolean> => {
  try {
    if (action.type === 'create_task') {
      const title = (action.title || 'Untitled Task').trim();
      const res = await productivityApi.getTasks({ query: title });
      return Boolean(res?.items?.some((t) => t.title.toLowerCase() === title.toLowerCase()));
    } else if (action.type === 'create_project') {
      const name = (action.name || action.title || 'Untitled Project').trim();
      const res = await productivityApi.getProjects({ query: name });
      return Boolean(res?.items?.some((p) => p.name.toLowerCase() === name.toLowerCase()));
    } else if (action.type === 'create_goal') {
      const title = (action.title || action.name || 'Untitled Goal').trim();
      const res = await productivityApi.getGoals();
      return Boolean(res?.items?.some((g) => g.title.toLowerCase() === title.toLowerCase()));
    }
  } catch {
    // Non-blocking query failure
  }
  return false;
};

interface ActionProposalItemProps {
  action: any;
  conversationId?: string;
}

export const ActionProposalItem: React.FC<ActionProposalItemProps> = ({ action, conversationId: propConversationId }) => {
  const { user } = useAuth();
  const queryClient = useQueryClient();
  const context = useContext(MessageContext);
  const conversationId = propConversationId || context.conversationId;
  const createTaskMutation = useCreateTask(user?.id);
  const updateTaskMutation = useUpdateTask(user?.id);
  const createProjectMutation = useCreateProject(user?.id);
  const createGoalMutation = useCreateGoal(user?.id);
  const createReminderMutation = useCreateReminder(user?.id);
  const { data: tasksData } = useTasks();

  const actionKey = `auren_action_${user?.id || 'guest'}_${conversationId ? conversationId + '_' : ''}${action?.type}_${action?.title || action?.name || ''}_${action?.due_date || action?.target_date || ''}_${action?.priority || ''}`;

  const [status, setStatus] = useState<ActionLifecycleStatus>(() => {
    const saved = getStoredActionState(actionKey);
    if (saved && saved.status) {
      if (saved.status === 'executing') return 'failed'; // Reset interrupted in-flight execution
      return saved.status;
    }
    return 'proposed';
  });

  const [errorMsg, setErrorMsg] = useState<string | null>(() => {
    const saved = getStoredActionState(actionKey);
    return saved?.error || null;
  });

  if (!action || !action.type) return null;

  const handleExecute = async () => {
    if (status === 'executing' || status === 'completed') {
      return; // Idempotency guard: prevent duplicate concurrent or repeated clicks
    }

    if (!user) {
      const msg = 'Please sign in to update items in Life Management.';
      setErrorMsg(msg);
      setStatus('failed');
      return;
    }

    // If recovering from a prior failure/timeout, check if entity already exists on server before creating duplicate!
    if (status === 'failed') {
      setStatus('executing');
      const alreadyCreated = await checkExistingEntity(action);
      if (alreadyCreated) {
        setStatus('completed');
        setErrorMsg(null);
        persistActionState(actionKey, {
          status: 'completed',
          updatedAt: new Date().toISOString(),
        });
        return;
      }
    }

    setStatus('executing');
    setErrorMsg(null);
    persistActionState(actionKey, {
      status: 'executing',
      updatedAt: new Date().toISOString(),
    });

    let timedOut = false;
    const timeoutTimer = setTimeout(async () => {
      timedOut = true;
      // Do not assume failure; verify if server created it despite slow connection
      const exists = await checkExistingEntity(action);
      if (exists) {
        setStatus('completed');
        setErrorMsg(null);
        persistActionState(actionKey, {
          status: 'completed',
          updatedAt: new Date().toISOString(),
        });
      } else {
        const msg = 'Action request timed out. Retrying will verify existing records before creating.';
        setStatus('failed');
        setErrorMsg(msg);
        persistActionState(actionKey, {
          status: 'failed',
          error: msg,
          updatedAt: new Date().toISOString(),
        });
      }
    }, 15000);

    try {
      let createdEntity: any = null;
      if (action.type === 'complete_task') {
        let targetTaskId = action.task_id;
        if (!targetTaskId && tasksData?.items) {
          const needle = (action.title || action.name || '').toLowerCase().trim();
          const match = tasksData.items.find(
            (t) => t.title.toLowerCase().includes(needle) || needle.includes(t.title.toLowerCase())
          );
          if (match) {
            targetTaskId = match.id;
          }
        }
        if (targetTaskId) {
          createdEntity = await updateTaskMutation.mutateAsync({
            taskId: targetTaskId,
            input: { status: 'completed' },
          });
        } else {
          // If task wasn't in active list, record/complete it directly
          createdEntity = await createTaskMutation.mutateAsync({
            title: action.title || 'Completed Task',
            priority: 'medium',
            status: 'completed',
          });
        }
        queryClient.invalidateQueries({ queryKey: REMINDER_KEYS.all });
      } else if (action.type === 'create_task') {
        let browserTz = 'UTC';
        try {
          browserTz = Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
        } catch {
          browserTz = 'UTC';
        }
        const dueDate = action.due_date && String(action.due_date).trim() ? String(action.due_date).trim() : undefined;
        createdEntity = await createTaskMutation.mutateAsync({
          title: action.title || 'Untitled Task',
          priority: action.priority || 'medium',
          due_date: dueDate,
          ...(action.reminder_mode ? { reminder_mode: action.reminder_mode } : {}),
          ...(action.reminder_offset_minutes !== undefined ? { reminder_offset_minutes: Number(action.reminder_offset_minutes) } : {}),
          ...(action.reminder_is_alarm !== undefined ? { reminder_is_alarm: Boolean(action.reminder_is_alarm) } : {}),
          reminder_timezone: action.timezone || browserTz,
        });
        queryClient.invalidateQueries({ queryKey: REMINDER_KEYS.all });
      } else if (action.type === 'create_reminder') {
        let browserTz = 'UTC';
        try {
          browserTz = Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
        } catch {
          browserTz = 'UTC';
        }
        createdEntity = await createReminderMutation.mutateAsync({
          title: action.title || 'Personal Reminder',
          trigger_at: String(action.trigger_at || new Date(Date.now() + 3600 * 1000).toISOString()),
          timezone: action.timezone || browserTz,
          is_alarm: Boolean(action.is_alarm),
          priority: action.is_alarm ? 'alarm' : 'normal',
        });
      } else if (action.type === 'create_project') {
        createdEntity = await createProjectMutation.mutateAsync({
          name: action.name || action.title || 'Untitled Project',
          description: action.description,
        });
      } else if (action.type === 'create_goal') {
        const targetDate = action.target_date && String(action.target_date).trim() ? String(action.target_date).trim() : undefined;
        createdEntity = await createGoalMutation.mutateAsync({
          title: action.title || action.name || 'Untitled Goal',
          description: action.description,
          target_date: targetDate,
        });
      }

      clearTimeout(timeoutTimer);
      setStatus('completed');
      setErrorMsg(null);
      persistActionState(actionKey, {
        status: 'completed',
        entityId: createdEntity?.id,
        updatedAt: new Date().toISOString(),
      });
    } catch (err: any) {
      clearTimeout(timeoutTimer);
      if (!timedOut) {
        const msg = err.message || 'Action execution failed';
        setStatus('failed');
        setErrorMsg(msg);
        persistActionState(actionKey, {
          status: 'failed',
          error: msg,
          updatedAt: new Date().toISOString(),
        });
      }
    }
  };

  // Auto-execute completion on mount if user is signed in and action is complete_task
  useEffect(() => {
    if (action.type === 'complete_task' && status === 'proposed' && user) {
      handleExecute();
    }
  }, [action.type, status, user]);

  const getActionMeta = () => {
    switch (action.type) {
      case 'complete_task':
        return {
          icon: CheckCircle2,
          label: 'Task Completed',
          color: 'text-emerald-400',
          border: 'border-emerald-800/60',
          bg: 'bg-emerald-950/30',
          buttonText: 'Mark Completed',
          title: action.title || 'Completed Task',
        };
      case 'create_task':
        return {
          icon: CheckSquare,
          label: 'Task Proposal',
          color: 'text-indigo-400',
          border: 'border-indigo-800/60',
          bg: 'bg-indigo-950/30',
          buttonText: 'Add to Tasks',
          title: action.title,
        };
      case 'create_project':
        return {
          icon: FolderKanban,
          label: 'Project Proposal',
          color: 'text-emerald-400',
          border: 'border-emerald-800/60',
          bg: 'bg-emerald-950/30',
          buttonText: 'Create Project',
          title: action.name || action.title,
        };
      case 'create_goal':
        return {
          icon: Target,
          label: 'Goal Proposal',
          color: 'text-purple-400',
          border: 'border-purple-800/60',
          bg: 'bg-purple-950/30',
          buttonText: 'Set Goal',
          title: action.title || action.name,
        };
      case 'create_reminder':
        return {
          icon: BellRing,
          label: action.is_alarm ? 'Alarm Proposal' : 'Reminder Proposal',
          color: 'text-emerald-400',
          border: 'border-emerald-800/60',
          bg: 'bg-emerald-950/30',
          buttonText: 'Schedule Reminder',
          title: action.title || 'Personal Reminder',
        };
      default:
        return null;
    }
  };

  const meta = getActionMeta();
  if (!meta) return null;
  const Icon = meta.icon;

  return (
    <div className={`my-2 p-3.5 rounded-xl border ${meta.border} ${meta.bg} space-y-2.5 max-w-lg`}>
      <div className="flex items-center justify-between">
        <div className="flex items-center space-x-2">
          <Icon className={`w-4 h-4 ${meta.color}`} />
          <span className="text-xs font-semibold text-slate-200">{meta.label}</span>
        </div>
        <span className="text-[10px] text-slate-400 font-mono">
          {status === 'completed'
            ? 'Executed'
            : status === 'executing'
            ? 'Executing...'
            : status === 'failed'
            ? 'Execution failed'
            : 'Requires confirmation'}
        </span>
      </div>

      <div className="pl-6">
        <span className="text-xs font-medium text-slate-100 block">{meta.title}</span>
        {action.priority && (
          <span className="inline-block mt-1 text-[9px] uppercase tracking-wider font-semibold px-1.5 py-0.5 rounded bg-slate-900 border border-slate-800 text-slate-300">
            Priority: {action.priority}
          </span>
        )}
        {action.due_date && (
          <span className="inline-block ml-2 text-[10px] text-slate-400">
            Due: {action.due_date}
          </span>
        )}
        {action.description && (
          <p className="text-[11px] text-slate-400 mt-1">{action.description}</p>
        )}
      </div>

      {errorMsg && (
        <div className="text-[11px] text-rose-400 pl-6">{errorMsg}</div>
      )}

      <div className="pl-6 pt-1 flex items-center space-x-2">
        {status === 'completed' ? (
          <span className="flex items-center space-x-1.5 text-xs font-medium text-emerald-400 bg-emerald-950/60 px-2.5 py-1 rounded-lg border border-emerald-800/50">
            <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
            <span>{action.type === 'complete_task' ? 'Marked as Completed ✓' : 'Added to Life Management'}</span>
          </span>
        ) : status === 'executing' ? (
          <button
            type="button"
            disabled
            className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-indigo-700/60 text-white text-xs font-medium cursor-wait opacity-80"
          >
            <Loader2 className="w-3.5 h-3.5 animate-spin" />
            <span>{action.type === 'complete_task' ? 'Marking Completed...' : `Creating ${meta.label}...`}</span>
          </button>
        ) : status === 'failed' ? (
          <button
            type="button"
            onClick={handleExecute}
            className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-rose-600 hover:bg-rose-500 text-white text-xs font-medium transition shadow-md shadow-rose-600/20"
          >
            <RefreshCw className="w-3.5 h-3.5" />
            <span>Retry {meta.buttonText}</span>
          </button>
        ) : (
          <button
            type="button"
            onClick={handleExecute}
            disabled={
              createTaskMutation.isPending ||
              updateTaskMutation.isPending ||
              createProjectMutation.isPending ||
              createGoalMutation.isPending ||
              createReminderMutation.isPending
            }
            className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-medium transition shadow-md shadow-indigo-600/20 disabled:opacity-50"
          >
            <Plus className="w-3.5 h-3.5" />
            <span>{meta.buttonText}</span>
          </button>
        )}
      </div>
    </div>
  );
};

interface ActionProposalCardProps {
  payloadStr: string;
}

const ActionProposalCard: React.FC<ActionProposalCardProps> = ({ payloadStr }) => {
  let parsed: any = null;
  try {
    parsed = JSON.parse(payloadStr.trim());
  } catch {
    return null;
  }

  if (Array.isArray(parsed)) {
    return (
      <div className="space-y-2 my-3">
        {parsed.map((item, idx) => (
          <ActionProposalItem key={idx} action={item} />
        ))}
      </div>
    );
  }

  if (parsed && typeof parsed === 'object') {
    return <ActionProposalItem action={parsed} />;
  }

  return null;
};

interface FencedCodeBlockProps {
  language?: string;
  className?: string;
  children?: React.ReactNode;
}

const FencedCodeBlock: React.FC<FencedCodeBlockProps> = ({ language, className, children, ...props }) => {
  const [copied, setCopied] = useState(false);
  const codeString = String(children).replace(/\n$/, '');

  // Check if this is an interactive AUREN action proposal
  if (language === 'auren-action' || language === 'auren_action') {
    return <ActionProposalCard payloadStr={codeString} />;
  }

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(codeString);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Clipboard write failed
    }
  };

  return (
    <div className="relative group my-3 rounded-xl overflow-hidden border border-slate-800 bg-slate-900/90 shadow-lg">
      <div className="flex items-center justify-between px-3.5 py-1.5 bg-slate-950/80 border-b border-slate-800/80 text-[11px] font-mono text-slate-400">
        <span className="uppercase tracking-wider font-semibold text-indigo-400">
          {language || 'text'}
        </span>
        <button
          onClick={handleCopy}
          className="flex items-center space-x-1 hover:text-white px-2 py-0.5 rounded hover:bg-slate-800 transition"
          aria-label="Copy code to clipboard"
        >
          {copied ? (
            <>
              <Check className="h-3 w-3 text-emerald-400" />
              <span className="text-emerald-400 font-sans text-[10px]">Copied</span>
            </>
          ) : (
            <>
              <Copy className="h-3 w-3" />
              <span className="font-sans text-[10px]">Copy</span>
            </>
          )}
        </button>
      </div>
      <div className="p-3 overflow-x-auto text-xs font-mono leading-relaxed">
        <code className={className} {...props}>
          {children}
        </code>
      </div>
    </div>
  );
};

interface MessageContentProps {
  content: string;
  role: 'user' | 'assistant' | 'system';
  conversationId?: string;
  messageId?: string;
}

export const MessageContent: React.FC<MessageContentProps> = ({
  content,
  role,
  conversationId,
  messageId,
}) => {
  if (role === 'user') {
    return (
      <div className="whitespace-pre-wrap font-sans text-sm leading-relaxed text-slate-100">
        {content}
      </div>
    );
  }

  return (
    <MessageContext.Provider value={{ conversationId, messageId }}>
      <div className="markdown-prose text-sm leading-relaxed text-slate-200">
        <ReactMarkdown
          remarkPlugins={[remarkGfm, remarkMath]}
          rehypePlugins={[
            rehypeKatex,
            rehypeHighlight,
            [rehypeSanitize, markdownSanitizeSchema],
          ]}
          components={{
            pre: ({ children }) => <div className="my-2">{children}</div>,
            code: ({ node, className, children, ...props }: any) => {
              const match = /language-([a-zA-Z0-9_-]+)/.exec(className || '');
              const isBlock = Boolean(match) || (typeof children === 'string' && children.includes('\n'));
              if (isBlock) {
                return (
                  <FencedCodeBlock language={match ? match[1] : ''} className={className} {...props}>
                    {children}
                  </FencedCodeBlock>
                );
              }
              return (
                <code
                  className="px-1.5 py-0.5 rounded bg-slate-800/80 text-amber-300 font-mono text-xs border border-slate-700/60"
                  {...props}
                >
                  {children}
                </code>
              );
            },
            a: ({ node, ...props }) => (
              <a
                {...props}
                target="_blank"
                rel="noopener noreferrer"
                className="text-indigo-400 hover:text-indigo-300 underline underline-offset-2 transition"
              />
            ),
            h1: ({ node, ...props }) => (
              <h1 className="text-lg font-bold text-white mt-4 mb-2 pb-1 border-b border-slate-800" {...props} />
            ),
            h2: ({ node, ...props }) => (
              <h2 className="text-base font-semibold text-white mt-3 mb-1.5" {...props} />
            ),
            h3: ({ node, ...props }) => (
              <h3 className="text-sm font-semibold text-slate-100 mt-2 mb-1" {...props} />
            ),
            p: ({ node, ...props }) => <p className="mb-2 last:mb-0 leading-relaxed" {...props} />,
            ul: ({ node, ...props }) => <ul className="list-disc pl-5 mb-2 space-y-1" {...props} />,
            ol: ({ node, ...props }) => <ol className="list-decimal pl-5 mb-2 space-y-1" {...props} />,
            li: ({ node, ...props }) => <li className="pl-0.5" {...props} />,
            blockquote: ({ node, ...props }) => (
              <blockquote
                className="border-l-4 border-indigo-500/50 bg-slate-900/40 pl-3 py-1 my-2 italic text-slate-300 rounded-r"
                {...props}
              />
            ),
            table: ({ node, ...props }) => (
              <div className="overflow-x-auto my-3 border border-slate-800 rounded-xl">
                <table className="min-w-full divide-y divide-slate-800 text-xs" {...props} />
              </div>
            ),
            thead: ({ node, ...props }) => <thead className="bg-slate-900/80 text-slate-300 font-semibold" {...props} />,
            tbody: ({ node, ...props }) => <tbody className="divide-y divide-slate-800/60 bg-slate-950/40" {...props} />,
            tr: ({ node, ...props }) => <tr className="hover:bg-slate-900/40 transition" {...props} />,
            th: ({ node, ...props }) => <th className="px-3 py-2 text-left" {...props} />,
            td: ({ node, ...props }) => <td className="px-3 py-2 text-slate-300" {...props} />,
          }}
        >
          {content}
        </ReactMarkdown>
      </div>
    </MessageContext.Provider>
  );
};
